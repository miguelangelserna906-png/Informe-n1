public class TiposDatos1 {
    public static void main(String[] args) {
        System.out.println("Ejercicio N3: Tipos de Datos");

        // Variable tipo float
      
        float Tipofloat = 597000F;
        System.out.println("Dato tipo float llamado Tipofloat, su valor es: " + Tipofloat);

        // Variable tipo double
      
        double Tipodouble = 26540000000000D;
        System.out.println("Dato tipo double llamado Tipodouble, su valor es: " + Tipodouble);

        // Variable boolean
      
        boolean Tipoboolean = true;
        System.out.println("Dato tipo boolean llamado Tipoboolean, su valor es: " + Tipoboolean);
    }
}
