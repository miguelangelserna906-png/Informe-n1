public class TiposDatos{
  public static void main(String[] args){
    System.out.println("Ejercicio N3: Tipos de Datos");

    //Variable tipo byte

    byte Tipobyte = 100;
    System.out.println("Dato tipo Byte llamado Tipobyte, su valor es: " + Tipobyte);

    //Variable tipo short
    
    short Tiposhort = 30000;
    System.out.println("Dato tipo Short llamado Tiposhort, su valor es: " + Tiposhort);

    //Variable tipo int
    
    int Tipoint = 41000;
    System.out.println("Dato tipo Int llamado Tipoint, su valor es: " + Tipoint);

    //Variable tipo long

    long Tipolong = 926400000000000000L;
    System.out.println("Dato tipo Long llamado Tipolong, su valor es: " + Tipolong);
  }
}
